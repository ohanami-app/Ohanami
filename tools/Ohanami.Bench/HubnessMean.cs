using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Ohanami.Core.Embedding;
using Ohanami.Core.Embedding.Generated;
using Ohanami.Core.Models;

namespace Ohanami.Bench;

/// <summary>
/// 特徴ベクトル検索の補正(ADR 0051)の μ を作る。参照の語の一覧(<c>hubness-reference-ja.txt</c>。測った語のまま凍結してある)の各語を、製品と同じテキスト埋め込み
/// (CPU のエンコーダ・同じトークナイザ)でベクトルにして、平均(正規化し直さない)を取り、Core の生成ソース(<c>HubnessReferenceMean.g.cs</c>)に書く。
/// 生成ソースには、作ったときの埋め込みの model_id、一覧の SHA-256(ファイルのバイト列)、語数も入る(Core が実行時に model_id を表と突き合わせる)。
/// </summary>
internal static class HubnessMean
{
    /// <summary>参照の語の一覧のファイル名(リポジトリの tools/Ohanami.Bench/ にある)。</summary>
    public const string ReferenceFileName = "hubness-reference-ja.txt";

    /// <summary>生成ソースの、リポジトリの中の場所。</summary>
    public static readonly string GeneratedRelativePath = Path.Combine("src", "Ohanami.Core", "Embedding", "Generated", "HubnessReferenceMean.g.cs");

    /// <summary>
    /// 参照の語の一覧を読む。1 行 1 語。空行と、先頭が # の行は読み飛ばす。同じ語が 2 回あれば例外、語が 1 つも無くても例外。
    /// 戻り値の Sha256 は、ファイルのバイト列の SHA-256(16 進、大文字)。
    /// </summary>
    public static (IReadOnlyList<string> Words, string Sha256) ReadReference(string path)
    {
        if (!File.Exists(path)) throw new FileNotFoundException($"参照の語の一覧が無い: {path}");
        byte[] bytes = File.ReadAllBytes(path);
        string text = new UTF8Encoding(false, true).GetString(bytes);
        var words = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        int lineNo = 0;
        foreach (string raw in text.Split('\n'))
        {
            lineNo++;
            string line = raw.Trim();
            if (line.Length == 0 || line.StartsWith('#')) continue;
            if (!seen.Add(line)) throw new InvalidDataException($"{Path.GetFileName(path)} の {lineNo} 行目: 同じ語が 2 回ある: {line}");
            words.Add(line);
        }
        if (words.Count == 0) throw new InvalidDataException($"{Path.GetFileName(path)} に語が無い");
        return (words, Convert.ToHexString(SHA256.HashData(bytes)));
    }

    /// <summary>実行ファイルから親をたどって、リポジトリの根(<paramref name="relative"/> があるディレクトリ)を探す。</summary>
    public static string FindInRepository(string relative)
    {
        for (DirectoryInfo? d = new(AppContext.BaseDirectory); d is not null; d = d.Parent)
        {
            string candidate = Path.Combine(d.FullName, relative);
            if (File.Exists(candidate)) return candidate;
        }
        throw new ArgumentException($"{relative} が見つからない。引数で指す。");
    }

    /// <summary>ベクトルの平均(double で足して、float にする。正規化し直さない)。次元がそろっていなければ例外。</summary>
    public static float[] Mean(IReadOnlyList<float[]> vectors)
    {
        ArgumentNullException.ThrowIfNull(vectors);
        if (vectors.Count == 0) throw new ArgumentException("ベクトルが無い", nameof(vectors));
        int dim = vectors[0].Length;
        var sum = new double[dim];
        foreach (float[] v in vectors)
        {
            if (v.Length != dim) throw new ArgumentException("ベクトルの次元がそろっていない", nameof(vectors));
            for (int d = 0; d < dim; d++) sum[d] += v[d];
        }
        var mean = new float[dim];
        for (int d = 0; d < dim; d++) mean[d] = (float)(sum[d] / vectors.Count);
        return mean;
    }

    /// <summary>
    /// 参照の語を、製品と同じテキスト埋め込み(CPU)でベクトルにして、平均 μ を返す。
    /// <paramref name="report"/> があれば、テキスト側の読み込みと、語の埋め込みにかかった秒数を 1 行ずつ渡す(埋め込みだけの時間を見るため)。
    /// </summary>
    public static float[] ComputeMean(string modelsDirectory, IReadOnlyList<string> words, Action<string>? report = null)
    {
        var clock = System.Diagnostics.Stopwatch.StartNew();
        EmbeddingModelSpec spec = ModelCatalog.Current;
        string modelDir = Path.Combine(modelsDirectory, BenchRunner.ModelDirectoryName);
        var vectors = new List<float[]>(words.Count);
        using Siglip2TextEncoder encoder = Siglip2TextEncoder.Create(modelDir, spec);
        Siglip2Tokenizer tokenizer = Siglip2Tokenizer.Load(ModelVerifier.PathOf(modelDir, spec.File(ModelRole.Tokenizer)));
        report?.Invoke(string.Create(CultureInfo.InvariantCulture, $"  テキスト側の読み込み {clock.Elapsed.TotalSeconds:F1} 秒"));
        clock.Restart();
        foreach (string w in words)
        {
            float[] v = encoder.EmbedQuery(w, tokenizer);
            if (v.Length != spec.Dim || v.Any(x => !float.IsFinite(x))) throw new InvalidDataException("参照の語のベクトルが壊れている(次元か有限でない値)");
            vectors.Add(v);
        }
        report?.Invoke(string.Create(CultureInfo.InvariantCulture, $"  {words.Count} 語の埋め込み {clock.Elapsed.TotalSeconds:F1} 秒"));
        return Mean(vectors);
    }

    /// <summary>Core の生成ソース(<c>HubnessReferenceMean.g.cs</c>)の本文。同じ入力なら同じバイト列になる(float は往復できる書式 "R")。</summary>
    public static string RenderSource(string modelId, string referenceSha256, int wordCount, float[] mean)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append("// tools/Ohanami.Bench の hubness-mean コマンドが生成した。手で編集しないこと。\n");
        sb.Append("// 参照の語の一覧(tools/Ohanami.Bench/hubness-reference-ja.txt)のテキスト埋め込みの平均 μ。使い方は ADR 0051。\n");
        sb.Append("// </auto-generated>\n");
        sb.Append("namespace Ohanami.Core.Embedding.Generated;\n\n");
        sb.Append("internal static class HubnessReferenceMean\n{\n");
        sb.Append("    /// <summary>μ を作ったときの埋め込みモデルの model_id。ベクトルの表の model_id と違えば、補正は使えない(Core が例外にする)。</summary>\n");
        sb.Append("    public const string ModelId = \"").Append(modelId).Append("\";\n\n");
        sb.Append("    /// <summary>参照の語の一覧のファイル(バイト列)の SHA-256(16 進、大文字)。</summary>\n");
        sb.Append("    public const string ReferenceSha256 = \"").Append(referenceSha256).Append("\";\n\n");
        sb.Append("    /// <summary>参照の語の数。</summary>\n");
        sb.Append("    public const int WordCount = ").Append(wordCount.ToString(CultureInfo.InvariantCulture)).Append(";\n\n");
        sb.Append("    /// <summary>μ(").Append(mean.Length.ToString(CultureInfo.InvariantCulture)).Append(" 個。参照のベクトルの平均で、正規化し直していない)。</summary>\n");
        sb.Append("    public static readonly float[] Mean =\n    [\n");
        for (int i = 0; i < mean.Length; i += 6)
        {
            sb.Append("       ");
            foreach (float x in mean.Skip(i).Take(6)) sb.Append(' ').Append(x.ToString("R", CultureInfo.InvariantCulture)).Append("f,");
            sb.Append('\n');
        }
        sb.Append("    ];\n}\n");
        return sb.ToString();
    }

    /// <summary>run の要約に書く、補正の出どころ(数字だけ)。生成ソースの中身をそのまま読む。</summary>
    public static string SourceLine() =>
        $"特徴ベクトル検索の補正(ADR 0051): 日本語の文字があり {Ohanami.Core.Search.HubnessGate.MaxCodePoints} 字以下の検索語に、参照の語の平均 μ を引く。"
        + $"μ の出どころ: 参照の一覧の SHA-256 {HubnessReferenceMean.ReferenceSha256}、{HubnessReferenceMean.WordCount} 語、model_id {HubnessReferenceMean.ModelId}";
}
