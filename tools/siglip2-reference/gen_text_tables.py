"""テキスト前処理の変換表を、参照の Python から生成して C# のソースに書き出す。

使い方(リポジトリの外の venv で):
    <venv>/Scripts/python.exe -I -X utf8 tools/siglip2-reference/gen_text_tables.py

出力: src/Ohanami.Core/Embedding/Generated/PythonTextTables.g.cs

C# の .NET と Python では、次の2つの定義が違う。参照の clean_text に合わせるため、Python が実際に返す結果を
表にして、C# には表だけを持たせる(ランタイムの Unicode のバージョン差に依存しない)。
  - 空白: `" ".join(text.split())` が空白として扱う文字(str.isspace() が真の文字)
  - 小文字化: `str.lower()` が1文字を1文字に写す文字の対応(U+0130 は2文字になるので含めない)
U+03A3(Σ)は、Python が語末で ς、それ以外で σ にする(文脈で変わる)。表には単独のときの σ を入れ、
比較のコーパスからは外す(gen_tokenizer_corpus.py の check_exclusions)。
"""
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "src", "Ohanami.Core", "Embedding", "Generated", "PythonTextTables.g.cs")


def main():
    ws = [cp for cp in range(0x110000) if not (0xD800 <= cp <= 0xDFFF) and chr(cp).isspace()]
    # str.split() が空白として扱う文字と isspace() が一致することを確かめる
    for cp in ws:
        assert ("a" + chr(cp) + "b").split() == ["a", "b"], hex(cp)
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or cp in ws:
            continue
        assert ("a" + chr(cp) + "b").split() == ["a" + chr(cp) + "b"], hex(cp)

    pairs = []
    skipped = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        lo = c.lower()
        if lo == c:
            continue
        if len(lo) != 1:
            skipped.append(cp)
            continue
        pairs.append((cp, ord(lo)))

    def lines(values, per_line=12):
        out = []
        for i in range(0, len(values), per_line):
            out.append("        " + ", ".join(values[i:i + per_line]) + ",")
        return "\n".join(out)

    ws_text = lines([f"0x{cp:X}" for cp in ws])
    pair_text = lines([f"0x{a:X}, 0x{b:X}" for a, b in pairs], per_line=6)

    py = sys.version.split()[0]
    src = f"""// <auto-generated>
// tools/siglip2-reference/gen_text_tables.py が生成した。手で編集しないこと。
// 生成元: Python {py}、unicodedata {unicodedata.unidata_version}
// </auto-generated>
namespace Ohanami.Core.Embedding.Generated;

internal static class PythonTextTables
{{
    public const string PythonVersion = "{py}";
    public const string UnicodeVersion = "{unicodedata.unidata_version}";

    /// <summary>Python の str.split() が空白として扱う文字のコードポイント({len(ws)} 個)。</summary>
    public static readonly int[] WhitespaceCodePoints =
    [
{ws_text}
    ];

    /// <summary>Python の str.lower() が1文字を1文字に写す対応({len(pairs)} 組)。(元, 先)を並べた配列。</summary>
    public static readonly int[] LowercasePairs =
    [
{pair_text}
    ];

    /// <summary>lower() が2文字以上になるため表に入れなかったコードポイント。</summary>
    public static readonly int[] LowercaseSkipped = [{", ".join(f"0x{cp:X}" for cp in skipped)}];
}}
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf8", newline="\n") as f:
        f.write(src)
    print(f"空白 {len(ws)} 個、小文字化 {len(pairs)} 組、除外 {len(skipped)} 個 → {OUT}")
    print("空白:", " ".join(f"U+{cp:04X}" for cp in ws))


if __name__ == "__main__":
    sys.exit(main())
